/**
 * Generates netlify/edge-functions/lib/card-preview-data.js — the title, summary
 * and image behind the link preview of each card link (/cards/tk802/049), read by
 * netlify/edge-functions/card-preview.js.
 *
 * Separate from gen-preview-manifest.mjs because it changes on a different
 * schedule: re-run it when a card file changes (a new set, errata), not when
 * decklists do. A card missing from the output still works; its link just gets
 * the generic site preview.
 *
 *   node scripts/gen-card-previews.mjs
 *
 * The output is committed so no build-step wiring is required.
 */

import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { uvsId } from '../src/js/card_id.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const assets = path.join(root, 'src', 'assets')

const CDN_BASE = 'https://img.builduvs.com'
const SITE_BASE = 'https://builduvs.com'

// Same files and order as src/js/card_provider.js. Later files win a duplicate
// id, as they do in cardByUvsId, so a preview matches the card the link opens.
const CARD_FILES = [
  'fairytail.json', 'sf6-2026.json', 'tekken8.json', 'mha09.json', 'kaiju.json', 'teamhero.json', 'gg-critrole.json',
  'sjw-mha4.json', 'heroesclash.json', 'rampage_dlc.json', 'provs.json',
  'rampage.json', 'cards.json',
]

// Long enough to read most card text without a preview turning into a wall of it.
const MAX_DESCRIPTION = 280

const capitalize = s => s.charAt(0).toUpperCase() + s.slice(1)

function statsOf(c) {
  const stats = []
  if (c.type === 'attack') {
    stats.push(`${c.speed ?? '–'} speed`)
    if (c.attack_zone) stats.push(c.attack_zone)
    stats.push(`${c.damage ?? '–'} damage`)
  }
  if (c.type === 'character') {
    stats.push(`${c.hand_size ?? '–'} hand`, `${c.vitality ?? '–'} vitality`)
  } else if (c.difficulty != null) {
    stats.push(`${c.difficulty} difficulty`, `${c.control} control`)
  }
  return stats
}

function describe(c) {
  const lead = [capitalize(c.type), ...statsOf(c), c.extension].join(' · ')
  const full = `${lead}. ${(c.text || '').replace(/\s+/g, ' ').trim()}`.trim()
  if (full.length <= MAX_DESCRIPTION) return full
  return full.slice(0, MAX_DESCRIPTION - 1).replace(/\s+\S*$/, '') + '…'
}

const previews = {}
for (const f of CARD_FILES) {
  for (const c of JSON.parse(fs.readFileSync(path.join(assets, f), 'utf8'))) {
    if (!c.asset) c.asset = `${c.extension_short}/${c.card_number_image}`
    const id = uvsId(c)
    if (id) previews[id] = [c.name, describe(c), c.asset]
  }
}

// Data lives in lib/: Netlify registers only top-level files in
// netlify/edge-functions/ as functions.
const outFile = path.join(root, 'netlify', 'edge-functions', 'lib', 'card-preview-data.js')
fs.writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/gen-card-previews.mjs — do not edit by hand.\n` +
  `export const SITE_BASE = ${JSON.stringify(SITE_BASE)}\n` +
  `export const CDN_BASE = ${JSON.stringify(CDN_BASE)}\n` +
  `// uvs_id → [name, description, asset]\n` +
  `export default ${JSON.stringify(previews)}\n`,
)

const kb = Math.round(fs.statSync(outFile).size / 1024)
console.log(`Wrote ${Object.keys(previews).length} card previews to ${path.relative(root, outFile)} (${kb} KB)`)
